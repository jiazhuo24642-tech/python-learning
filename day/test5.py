# 位置参数    默认参数    可变参数    关键字参数 
# 命名关键字参数  需要一个特殊的分隔符 * , * 后的参数被视为命名关键字参数
# 默认参数必须指向不可变对象
def f1(a, b, c=0, *args, **kw):
    print('a =', a, 'b =', b, 'c =', c, 'args =', args, 'kw =', kw)

def f2(a, b, c=0, *, d, **kw):
    print('a =', a, 'b =', b, 'c =', c, 'd =', d, 'kw =', kw)

# 调用示例
f1(1, 2, 3, 'a', 'b', 'c', x=10, y=20)
f2(1, 2, 3, d=4, x=5, y=6)
